import uuid

from datetime import datetime

from sqlalchemy import (
    String,
    DateTime,
    Enum,
)

from sqlalchemy.dialects.postgresql import UUID

from sqlalchemy.orm import (
    Mapped,
    mapped_column,
)

from app.database.base import Base
from app.database.base_model import TimestampMixin
from app.models.enums import DeviceStatus


class Device(
    Base,
    TimestampMixin,
):
    """
    Android Calling Device Model
    """

    __tablename__ = "devices"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
    )

    device_name: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
    )

    device_identifier: Mapped[str] = mapped_column(
        String(255),
        unique=True,
        index=True,
        nullable=False,
    )

    # Permanent device identifier generated by the mobile app.
    # Phone number may not be available on modern Android versions,
    # so it is optional and can be assigned later by an administrator.
    phone_number: Mapped[str | None] = mapped_column(
        String(20),
        nullable=True,
    )

    status: Mapped[DeviceStatus] = mapped_column(
        Enum(DeviceStatus),
        default=DeviceStatus.OFFLINE,
        nullable=False,
    )

    current_call_id: Mapped[str | None] = mapped_column(
        String(100),
        nullable=True,
    )

    last_seen: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
    )

    def __repr__(self):
        return f"<Device {self.device_name}>"